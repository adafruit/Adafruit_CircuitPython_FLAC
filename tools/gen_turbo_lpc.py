"""Write the unrolled LPC predictors into src/flac_turbo.py (between the GENERATED markers).

Viper has no code generation at run time, so each common order gets its own function with
the taps written out. A pointer q that moves one sample per step makes every tap a load at
a constant offset (q[k] compiles to one ldr), and the coefficients sit in locals.

usage: python3 tools/gen_turbo_lpc.py
"""

import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, "src", "flac_turbo.py")
BEGIN = "# --- BEGIN GENERATED by tools/gen_turbo_lpc.py, do not edit ---\n"
END = "# --- END GENERATED ---\n"
MAX_ORDER = 12


def plain(n):
    cs = "\n".join("    c%d = co[%d]" % (j, j) for j in range(n))
    taps = " + ".join("c%d * q[%d]" % (j, n - 1 - j) for j in range(n))
    return f"""
@micropython.viper
def _lpc{n}(out: ptr32, co: ptr32, shift: int, n: int):
{cs}
    base = uint(out)
    i = {n}
    while i < n:
        q = ptr32(base + uint((i - {n}) << 2))
        q[{n}] += ({taps}) >> shift
        i += 1
"""


def split(n):
    cs = "\n".join("    c%d = co[%d]" % (j, j) for j in range(n))
    hi = " + ".join("c%d * (q[%d] >> b)" % (j, n - 1 - j) for j in range(n))
    lo = " + ".join("c%d * (q[%d] & lm)" % (j, n - 1 - j) for j in range(n))
    return f"""
@micropython.viper
def _lpcs{n}(out: ptr32, co: ptr32, shift: int, n: int, b: int):
{cs}
    lm = (1 << b) - 1
    # ((H << u) + (L >> v)) >> w == (H * 2**b + L) >> shift, see lpc_restore_split
    u = 0
    v = b
    w = shift - b
    if shift < b:
        u = b - shift
        v = shift
        w = 0
    base = uint(out)
    i = {n}
    while i < n:
        q = ptr32(base + uint((i - {n}) << 2))
        hs = {hi}
        ls = {lo}
        q[{n}] += ((hs << u) + (ls >> v)) >> w
        i += 1
"""


def dispatch():
    lines = [
        "",
        "@micropython.viper",
        "def lpc_run(out, co, order: int, shift: int, n: int, b: int, mode: int):",
        '    """Predict out[order:n] in place with the unrolled function for this order',
        '    (mode 0: one 32-bit sum, mode 1: split), or the general loop past order %d."""'
        % MAX_ORDER,
        "    if mode == 0:",
    ]
    # mode 0 nests its order checks; mode 1 continues the outer chain (elif), as ruff formats it
    for k in range(1, MAX_ORDER + 1):
        lines.append("        %s order == %d:" % ("if" if k == 1 else "elif", k))
        lines.append("            _lpc%d(out, co, shift, n)" % k)
    lines.append("        else:")
    lines.append("            lpc_restore(out, co, order, shift, n)")
    for k in range(1, MAX_ORDER + 1):
        lines.append("    elif order == %d:" % k)
        lines.append("        _lpcs%d(out, co, shift, n, b)" % k)
    lines.append("    else:")
    lines.append("        lpc_restore_split(out, co, order, shift, n, b)")
    return "\n".join(lines) + "\n"


def main():
    body = "".join(plain(n) for n in range(1, MAX_ORDER + 1))
    body += "".join(split(n) for n in range(1, MAX_ORDER + 1))
    body += dispatch()
    src = open(SRC).read()
    if BEGIN in src:
        head, rest = src.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
    else:
        head, tail = src.rstrip("\n") + "\n\n\n", ""
    open(SRC, "w").write(head + BEGIN + body + END + tail)
    print("wrote %d unrolled orders into %s" % (MAX_ORDER, SRC))


if __name__ == "__main__":
    main()
